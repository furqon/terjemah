def lookup(lemma: str) -> str:
    """Look up English translation for an Arabic lemma.

    Tries exact match first, then stripped (without tashkeel) match.

    Args:
        lemma: The Arabic word lemma (may or may not have diacritics).

    Returns:
        English translation string, or empty string if not found.
    """
    if not lemma:
        return ""

    # Try exact match first
    if lemma in ARABIC_ENGLISH:
        return ARABIC_ENGLISH[lemma]

    # Strip diacritics (tashkeel) and try again
    stripped = pyarabic.araby.strip_tashkeel(lemma)
    if stripped in ARABIC_ENGLISH:
        return ARABIC_ENGLISH[stripped]

    # Try matching stripped value against all keys
    for key, val in ARABIC_ENGLISH.items():
        key_stripped = pyarabic.araby.strip_tashkeel(key)
        if key_stripped == stripped:
            return val

    return ""
