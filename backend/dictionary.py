def lookup(lemma: str) -> str:
    """Look up Indonesian translation for an Arabic lemma.

    Tries exact match first, then stripped (without tashkeel) match.

    Args:
        lemma: The Arabic word lemma (may or may not have diacritics).

    Returns:
        Indonesian translation string, or empty string if not found.
    """
    if not lemma:
        return ""

    # Try exact match first
    if lemma in ARABIC_INDONESIAN:
        return ARABIC_INDONESIAN[lemma]

    # Strip diacritics (tashkeel) and try again
    stripped = pyarabic.araby.strip_tashkeel(lemma)
    if stripped in ARABIC_INDONESIAN:
        return ARABIC_INDONESIAN[stripped]

    # Try matching stripped value against all keys (handles case where
    # the lemma has extra characters not in the stripped version)
    for key, val in ARABIC_INDONESIAN.items():
        key_stripped = pyarabic.araby.strip_tashkeel(key)
        if key_stripped == stripped:
            return val

    return ""

